"""业务概念词典。用来把「同义不同形」的问题拉到一起。

纯 2-gram 相似度只能抓「措辞几乎一样」的：
    这个多少钱 ≈ 多少钱啊   ✅
    这个多少钱 ≈ 价格是多少  ❌（字面完全不同）

加一层概念标签后，第二种也能归并。这层完全免费，而且比 embedding 更可控 ——
词表是可以被业务方直接审阅和修改的。
"""

