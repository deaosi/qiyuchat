# 只有这些概念才允许「跨簇合并」—— 太泛的概念（质量、使用）合并容易出错
MERGEABLE = {
    "价格", "发货", "物流", "退货", "退款", "换货", "库存",
    "发票", "安装", "保修", "配件", "投诉",
}

_COMPILED = {k: re.compile("|".join(re.escape(w) for w in v)) for k, v in CONCEPTS.items()}


def concept_signature(text: str) -> frozenset[str]:
    """返回这段文本命中的所有业务概念。"""
    if not text:
        return frozenset()
    return frozenset(name for name, pat in _COMPILED.items() if pat.search(text))


def dominant_concept(texts: list[str], min_ratio: float = 0.6) -> str:
    """一组问题的「主导概念」。占比不够就不算，避免乱合并。"""
    if not texts:
        return ""
    counts: dict[str, int] = {}
    for t in texts:
        for c in concept_signature(t):
            counts[c] = counts.get(c, 0) + 1
    if not counts:
        return ""
    name, n = max(counts.items(), key=lambda kv: kv[1])
    if n / len(texts) < min_ratio:
        return ""
    return name if name in MERGEABLE else ""
